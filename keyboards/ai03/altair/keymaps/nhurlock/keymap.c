bool get_permissive_hold(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        default:
            return false;
    }
}

bool get_hold_on_other_key_press(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case LCTL_T(KC_TAB):
        case LSFT_T(KC_ESC):
        case LT(SPECIALS, KC_SPC):
            return true;
        default:
            return false;
    }
}
